function t(key, vars) {
  const dict = I18N_DICT[LANG] || I18N_DICT.en;
  let s = dict[key] ?? key;
  if (vars !== undefined) {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}

